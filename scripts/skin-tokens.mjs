// The token report of the reference skin (ADR 0023, K320-9; ADR 0025): every
// `--qt-*` token that packages/vue/styles/table.css defines on `:root`, with
// its light default and its dark default. The tokens are the skin's public
// surface: a product themes the skin by setting them, so a token is never
// renamed or removed (ADR 0019: no major release to do it in).
//
//   node scripts/skin-tokens.mjs           rewrites packages/vue/etc/tokens.md
//   node scripts/skin-tokens.mjs --check   fails when the report is stale
//
// Both fail when a token is gone from the stylesheet that the report lists,
// or that the report of the latest release tag lists: removing a token from
// the stylesheet and the report together still fails. A release's report is
// read where that release kept it: packages/vue/etc/tokens.md since the
// skin moved into the Vue package (3.23.0), packages/query-table-skin/etc/
// tokens.md up to 3.22.0. They need the release tags (`git fetch --tags`).
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const vue = join(root, 'packages', 'vue')
const cssPath = join(vue, 'styles', 'table.css')
const reportPath = join(vue, 'etc', 'tokens.md')

/** Where a release kept its token report: the current path first. */
const releasedReports = [
  'packages/vue/etc/tokens.md',
  'packages/query-table-skin/etc/tokens.md'
]

const read = path => readFileSync(path, 'utf8').replace(/\r\n/g, '\n')
const css = read(cssPath).replace(/\/\*[\s\S]*?\*\//g, '')

/** The declarations `--qt-x: value` of the first block opened by `opener`. */
const blockOf = opener => {
  const start = css.indexOf(opener)
  if (start < 0) {
    throw new Error(`table.css has no \`${opener}\` block`)
  }
  const body = css.slice(start + opener.length, css.indexOf('}', start))
  return new Map(
    [...body.matchAll(/(--qt-[\w-]+)\s*:\s*([^;]+);/g)].map(
      ([, name, value]) => [name, value.replace(/\s+/g, ' ').trim()]
    )
  )
}

const light = blockOf(':root {')
const dark = blockOf(":root[data-theme='dark'] {")

const cell = text => `\`${text.replace(/\|/g, '\\|')}\``
const report = [
  '# Tokens of the reference skin, @dolusoft/query-table/table.css',
  '',
  '<!-- Generated by scripts/skin-tokens.mjs from styles/table.css. Do not edit: change the stylesheet and run `pnpm skin:update`. -->',
  '',
  'Every `--qt-*` custom property the stylesheet defines on `:root`. Set them on `:root` (or on a wrapper) to theme the table. A token is never renamed or removed; a new one may be added (ADR 0023, ADR 0025). The dark column is the value under `prefers-color-scheme: dark` and `data-theme="dark"`; empty means the light value holds.',
  '',
  '| Token | Light | Dark |',
  '| --- | --- | --- |',
  ...[...light].map(
    ([name, value]) =>
      `| ${cell(name)} | ${cell(value)} | ${dark.has(name) ? cell(dark.get(name)) : ''} |`
  ),
  ''
].join('\n')

/** The token names a report lists. */
const namesIn = text =>
  [...text.replace(/\r\n/g, '\n').matchAll(/^\| `(--qt-[\w-]+)` \|/gm)].map(
    ([, name]) => name
  )

const git = args =>
  execFileSync('git', args, {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore']
  })

/**
 * The tokens of the newest release tag that has a token report, or null
 * before the skin's first release.
 */
const releasedTokens = () => {
  let tags = []
  try {
    tags = git(['tag', '--list', 'v*', '--sort=-v:refname'])
      .split('\n')
      .filter(Boolean)
  } catch {
    // Not a git checkout: reported below as no tags.
  }
  if (tags.length === 0) {
    console.error(
      '[skin-tokens] No released v* tag found: fetch the tags (`git fetch --tags`) before the check.'
    )
    process.exit(1)
  }
  for (const tag of tags) {
    for (const path of releasedReports) {
      let text
      try {
        text = git(['show', `${tag}:${path}`])
      } catch {
        continue // Not at this path in this release.
      }
      return { tag, names: namesIn(text) }
    }
    // The skin is not in this release.
  }
  return null
}

const released = releasedTokens()
const listed = existsSync(reportPath) ? namesIn(read(reportPath)) : []
const removed = [...new Set([...(released?.names ?? []), ...listed])].filter(
  name => !light.has(name)
)
if (removed.length > 0) {
  console.error(
    `[skin-tokens] table.css no longer defines ${removed.join(', ')} (listed by packages/vue/etc/tokens.md${released ? ` or by its ${released.tag} release` : ''}). A token of the reference skin is never renamed or removed (ADR 0023, K320-9): put it back, and add a new token next to it if the meaning changed.`
  )
  process.exit(1)
}
const strayDark = [...dark.keys()].filter(name => !light.has(name))
if (strayDark.length > 0) {
  console.error(
    `[skin-tokens] the dark theme sets ${strayDark.join(', ')}, which :root does not define.`
  )
  process.exit(1)
}

if (process.argv.includes('--check')) {
  if (!existsSync(reportPath) || read(reportPath) !== report) {
    console.error(
      '[skin-tokens] packages/vue/etc/tokens.md is stale: run `pnpm skin:update` and review the token diff.'
    )
    process.exit(1)
  }
  console.log(
    `[skin-tokens] ${light.size} tokens, report up to date, ${released ? `every token of ${released.tag} kept` : 'no release of the skin yet'}`
  )
} else {
  writeFileSync(reportPath, report)
  console.log(
    `[skin-tokens] wrote packages/vue/etc/tokens.md (${light.size} tokens)`
  )
}
